package io.airlift.vthreadtime;

import java.lang.classfile.ClassFile;
import java.lang.classfile.ClassModel;
import java.lang.classfile.ClassTransform;
import java.lang.classfile.CodeBuilder;
import java.lang.classfile.CodeElement;
import java.lang.classfile.CodeTransform;
import java.lang.classfile.Label;
import java.lang.classfile.MethodModel;
import java.lang.classfile.MethodTransform;
import java.lang.classfile.instruction.ReturnInstruction;
import java.lang.constant.ClassDesc;
import java.lang.constant.MethodTypeDesc;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.util.List;

import static java.lang.constant.ConstantDescs.MTD_void;
import static java.lang.reflect.AccessFlag.STATIC;

/// Rewrites `java.lang.VirtualThread` so that its mount and unmount paths call into the
/// boot-loaded hook class.
///
/// The hook class is named only as a constant-pool entry: it is defined into the bootstrap
/// loader at runtime, so this module must never reference it as a Java symbol.
///
/// Every injection is the guarded call `if (this.threadLocals() != null) hook()`. A virtual
/// thread that never touched a `ThreadLocal` has no map and cannot be registered, and skipping
/// the call keeps `ThreadLocal.get()` inside the hook from allocating a map for every
/// unregistered virtual thread in the JVM.
final class VirtualThreadTransformer
{
    private static final String CLASS_NAME = "java/lang/VirtualThread";
    private static final ClassDesc HOOKS = ClassDesc.of("io.airlift.vthreadtime.hook.VirtualThreadHooks");
    private static final ClassDesc THREAD = ClassDesc.of("java.lang.Thread");
    private static final String THREAD_LOCALS_NAME = "threadLocals";
    private static final String THREAD_LOCAL_MAP_NAME = "java.lang.ThreadLocal$ThreadLocalMap";
    private static final MethodTypeDesc THREAD_LOCALS = MethodTypeDesc.of(ClassDesc.of(THREAD_LOCAL_MAP_NAME));

    // mount() sets the current thread to the virtual thread as its last action and unmount()
    // resets it as its first, so the hooks sit right at the method exit and entry to run with
    // the virtual thread current.
    private static final List<HookSite> HOOK_SITES = List.of(
            new HookSite("mount", MTD_void, beforeReturns("mounted")),
            new HookSite("unmount", MTD_void, new EntryHook("unmounted")));

    private VirtualThreadTransformer() {}

    /// Returns the transformed class file.
    ///
    /// @throws IllegalStateException if the bytes are not `java.lang.VirtualThread`, lack a
    ///         hooked method, or the running JDK's `Thread` lacks the accessor the injected
    ///         code calls, so the caller can fail the installation
    static byte[] transform(byte[] classFile)
    {
        checkThreadLocalsAccessor(Thread.class);
        ClassFile api = ClassFile.of();
        ClassModel model = api.parse(classFile);
        String className = model.thisClass().asInternalName();
        if (!className.equals(CLASS_NAME)) {
            throw new IllegalStateException("Expected class %s but found %s".formatted(CLASS_NAME, className));
        }
        for (HookSite site : HOOK_SITES) {
            MethodModel method = model.methods().stream()
                    .filter(site::matches)
                    .findFirst()
                    .orElseThrow(() -> new IllegalStateException("%s has no method %s".formatted(CLASS_NAME, site)));
            // The injected code loads slot 0 as the receiver of threadLocals()
            if (method.flags().has(STATIC)) {
                throw new IllegalStateException("%s.%s is static".formatted(CLASS_NAME, site));
            }
        }

        // Untouched methods are copied byte for byte because the constant pool is shared with the
        // original; stack maps and max stack of the hooked methods are regenerated by the API.
        ClassTransform transform = (classBuilder, element) -> {
            if (element instanceof MethodModel method) {
                for (HookSite site : HOOK_SITES) {
                    if (site.matches(method)) {
                        classBuilder.transformMethod(method, MethodTransform.transformingCode(site.code()));
                        return;
                    }
                }
            }
            classBuilder.with(element);
        };
        return api.transformClass(model, transform);
    }

    /// Checks that `thread` declares the instance method `threadLocals()` returning
    /// `ThreadLocal.ThreadLocalMap`, which the injected code calls. Retransformation does not
    /// resolve the call, so without this check a JDK that renamed the accessor would throw
    /// `NoSuchMethodError` from the first `mount()` instead of failing the installation.
    ///
    /// @throws IllegalStateException if the accessor is missing or has another shape
    static void checkThreadLocalsAccessor(Class<?> thread)
    {
        Method accessor;
        try {
            accessor = thread.getDeclaredMethod(THREAD_LOCALS_NAME);
        }
        catch (NoSuchMethodException e) {
            throw new IllegalStateException("%s has no method %s()".formatted(thread.getName(), THREAD_LOCALS_NAME), e);
        }
        if (Modifier.isStatic(accessor.getModifiers())) {
            throw new IllegalStateException("%s.%s() is static".formatted(thread.getName(), THREAD_LOCALS_NAME));
        }
        String returnType = accessor.getReturnType().getName();
        if (!returnType.equals(THREAD_LOCAL_MAP_NAME)) {
            throw new IllegalStateException("%s.%s() returns %s, not %s".formatted(thread.getName(), THREAD_LOCALS_NAME, returnType, THREAD_LOCAL_MAP_NAME));
        }
    }

    /// Calls the hook immediately before every `return`.
    ///
    /// Labels bound at a return instruction are delivered before it, so jumps to a shared
    /// `return` land on the hook, not past it.
    private static CodeTransform beforeReturns(String hook)
    {
        return (code, element) -> {
            if (element instanceof ReturnInstruction) {
                emitHook(code, hook);
            }
            code.with(element);
        };
    }

    private static void emitHook(CodeBuilder code, String hook)
    {
        Label skip = code.newLabel();
        code.aload(0)
                .invokevirtual(THREAD, THREAD_LOCALS_NAME, THREAD_LOCALS)
                .ifnull(skip)
                .invokestatic(HOOKS, hook, MTD_void)
                .labelBinding(skip);
    }

    /// Calls the hook before any original element, including labels bound at offset zero.
    private record EntryHook(String hook)
            implements CodeTransform
    {
        @Override
        public void atStart(CodeBuilder code)
        {
            emitHook(code, hook);
        }

        @Override
        public void accept(CodeBuilder code, CodeElement element)
        {
            code.with(element);
        }
    }

    private record HookSite(String name, MethodTypeDesc type, CodeTransform code)
    {
        boolean matches(MethodModel method)
        {
            return method.methodName().equalsString(name) && method.methodType().equalsString(type.descriptorString());
        }

        @Override
        public String toString()
        {
            return name + type.descriptorString();
        }
    }
}
